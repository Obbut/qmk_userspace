/// Generated QMK files for one firmware definition.
struct GeneratedArtifacts {
    /// The complete generated `keymap.c`.
    let keymapC: String

    /// The complete generated `config.h`.
    let configH: String

    /// The complete generated `rules.mk`.
    let rulesMK: String

    /// The generated metadata boundary consumed by the protocol runtime.
    let metadataH: String

    /// The generated keymap-drawer document.
    let keymapDrawerYAML: String
}
